import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
const source = (await Promise.all(['library-bundle.js', 'ai-profiles.js', 'ai-prompts.js'].map(name => readFile(new URL('../src/' + name, import.meta.url), 'utf8')))).join('\n');
const api = runInNewContext(source + '\n({normalizeAiGame,aiGameChoice,aiGameInstructions,aiGameWarnings,aiGameConnections,aiGameConnectionText,aiGameMediaRecipe,libraryReference,localLibraryReference,aiPromptText})', { document: { querySelector: () => ({}) } });
assert.equal(api.aiGameChoice().id, 'canvas');
assert.equal(api.aiGameChoice({ genre: 'platformer' }).id, 'phaser3');
assert.equal(api.aiGameChoice({ physics: 'bodies' }).id, 'matter');
assert.equal(api.aiGameChoice({ dimension: '3d' }).id, 'three');
assert.equal(api.aiGameChoice({ dimension: '3d', basis: 'babylon' }).id, 'babylon');
assert.equal(api.aiGameWarnings({ dimension: '3d', basis: 'babylon' }).length, 0);
assert.match(api.aiGameInstructions({ dimension: '3d', basis: 'babylon' }), /BABYLON.*Engine/);
assert.match(api.aiGameInstructions({ dimension: '3d', basis: 'babylon' }), /babylonjs@9\.30\.0/);
assert.match(api.aiGameMediaRecipe('babylon'), /DynamicTexture/);
assert.equal(api.aiGameChoice({ dimension: '3d', basis: 'phaser4' }).id, 'phaser4');
assert(api.aiGameWarnings({ dimension: '3d', basis: 'phaser4' }).length);
assert(api.aiGameWarnings({ dimension: '3d', physics: 'bodies' }).length);
assert.equal(api.normalizeAiGame({ basis: '__proto__', genre: '<script>', style: 'constructor' }).basis, 'auto');
assert.equal(api.normalizeAiGame({ basis: { toString: null }, dimension: [] }).basis, 'auto');
const phaser = 'https://cdn.jsdelivr.net/npm/phaser@4.2.1/dist/phaser.min.js';
assert.equal(api.libraryReference(phaser).key, 'phaser@4.2.1');
assert.equal(api.libraryReference(phaser.replace('4.2.1', '4.99.0')), null);
assert.equal(api.localLibraryReference('../libs/phaser-4.2.1.min.js').key, 'phaser@4.2.1');
assert.equal(api.localLibraryReference('./vendor/phaser/4.2.1/phaser.min.js').key, 'phaser@4.2.1');
const tag = `<script src="${phaser}"></script>`;
assert.equal(api.aiGameConnections(`<!--${tag}--><template>${tag}</template><noscript>${tag}</noscript><script>const s='${tag.replace('</script>', '<\\/script>')}';</script>`).found.length, 0);
assert.equal(api.aiGameConnections(tag).found[0].key, 'phaser@4.2.1');
assert.equal(api.aiGameConnections('<script type="text/plain" src="' + phaser + '"></script>').found.length, 0);
assert.equal(api.aiGameConnections('<script src="custom.js"></script>').unknown.length, 1);
assert.match(api.aiGameConnectionText('<canvas></canvas>', 'phaser3'), /Ожидаемое подключение не найдено/);
assert.match(api.aiGameConnectionText(tag, 'phaser3'), /отличающиеся версии/);
assert.match(api.aiGameConnectionText(tag, 'canvas'), /дополнительные библиотеки/);
const game = { genre: 'platformer', style: 'paper', basis: 'phaser4' };
assert.match(api.aiGameInstructions(game), /4\.2\.1/);
assert.match(api.aiGameInstructions(game), /бумажных/);
assert.match(api.aiGameInstructions(game), /Прыжок/);
assert(!api.aiGameInstructions({ genre: 'puzzle' }).includes('Прыжок'));
assert.match(api.aiGameMediaRecipe('phaser4'), /textures.addImage/);
assert.match(api.aiGameMediaRecipe('three'), /THREE.Texture/);
for (const mode of ['change', 'fix']) {
  const prompt = api.aiPromptText({ mode, project: 'game', platform: 'mobile', task: 'Сделай героя красным', game: JSON.stringify(game) }, '<canvas></canvas>', []);
  assert.match(prompt, /точные версии библиотек текущего кода/);
  assert(!prompt.includes(phaser), 'A past creation preference must not migrate the current game');
}
console.log('Game requirements, independent style, exact versions, inert observations and preservation of actual code passed.');
